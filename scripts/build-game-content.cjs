// Compile server/data/game_content.json into the seed rows that Nakama inserts
// into the game_* PostgreSQL tables on boot. Seeds only add missing rows; the
// database is the live source of truth after the first boot.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const source = JSON.parse(fs.readFileSync(path.join(root, 'server/data/game_content.json'), 'utf8'));
const ID = /^[a-z0-9_:]{2,60}$/, RARITY = ['thuong','linh','hiem','la'], VI = ['tho','thuy','thach','moc','phong'];
const int = (v, min, max) => Number.isInteger(v) && v >= min && v <= max;
function check(ok, message) { if (!ok) throw Error('Invalid game content: ' + message); }
check(source.schema_version === 1, 'schema_version');
const items = new Set();
const rows = {game_items: [], game_crops: [], game_loot: [], game_recipes: [], game_recipe_ingredients: []};
source.items.forEach((it, i) => {
  check(ID.test(it.id) && !items.has(it.id) && typeof it.name === 'string' && it.name, 'item ' + it.id);
  items.add(it.id);
  const instance = !!it.instance, bound = !!it.bound, stackMax = it.stackMax ?? (instance || bound ? 1 : 99);
  check(int(stackMax, 1, 99) && (!instance || stackMax === 1), 'stackMax ' + it.id);
  check(RARITY.includes(it.rarity ?? 'thuong'), 'rarity ' + it.id);
  check((it.absorbVi === undefined) === (it.absorbMotes === undefined) && (it.absorbVi === undefined || (VI.includes(it.absorbVi) && int(it.absorbMotes, 1, 50))), 'absorb ' + it.id);
  for (const k of ['attackBonus','defenseBonus','healAmount','buyPrice','sellPrice']) check(it[k] === undefined || int(it[k], 0, 100000), k + ' ' + it.id);
  rows.game_items.push({id: it.id, name: it.name, rarity: it.rarity ?? 'thuong', stack_max: stackMax, instance, bound,
    equip_slot: it.equipSlot ?? null, attack_bonus: it.attackBonus ?? null, defense_bonus: it.defenseBonus ?? null,
    heal_amount: it.healAmount ?? null, buy_price: it.buyPrice ?? null, sell_price: it.sellPrice ?? null,
    absorb_vi: it.absorbVi ?? null, absorb_motes: it.absorbMotes ?? null, sort_order: i});
});
source.crops.forEach((c, i) => {
  check(ID.test(c.id) && items.has(c.seed) && items.has(c.output) && (c.glow === undefined || items.has(c.glow)), 'crop ' + c.id);
  check(int(c.durationMs, 1000, 86400000) && int(c.yield, 1, 99) && [c.seedBackPercent, c.glowPercent, c.glowNightPercent].every(p => int(p, 0, 100)), 'crop numbers ' + c.id);
  rows.game_crops.push({id: c.id, seed_item: c.seed, output_item: c.output, glow_item: c.glow ?? null, duration_ms: c.durationMs,
    yield_count: c.yield, seed_back_percent: c.seedBackPercent, glow_percent: c.glowPercent, glow_night_percent: c.glowNightPercent, sort_order: i});
});
for (const [table, entries] of Object.entries(source.loot)) {
  check(ID.test(table) && entries.length > 0 && new Set(entries.map(e => e[0])).size === entries.length, 'loot table ' + table);
  entries.forEach(([itemId, weight, quantity], i) => {
    check(items.has(itemId) && int(weight, 1, 1000000) && int(quantity, 1, 99), 'loot ' + table + '/' + itemId);
    rows.game_loot.push({table_id: table, item_id: itemId, weight, quantity, sort_order: i});
  });
}
source.recipes.forEach((r, i) => {
  check(ID.test(r.id) && items.has(r.output) && int(r.fee, 0, 100000) && Object.keys(r.ingredients).length > 0, 'recipe ' + r.id);
  rows.game_recipes.push({id: r.id, output_item: r.output, fee: r.fee, sort_order: i});
  for (const [itemId, quantity] of Object.entries(r.ingredients)) {
    check(items.has(itemId) && int(quantity, 1, 99), 'ingredient ' + r.id + '/' + itemId);
    rows.game_recipe_ingredients.push({recipe_id: r.id, item_id: itemId, quantity});
  }
});
const output = '// Generated by scripts/build-game-content.cjs; edit server/data/game_content.json instead.\n' +
  'const GAME_CONTENT_SEED: {[table: string]: {[column: string]: string | number | boolean | null}[]} = {\n' +
  Object.keys(rows).map(t => '  ' + t + ': [\n' + rows[t].map(r => '    ' + JSON.stringify(r)).join(',\n') + '\n  ]').join(',\n') + '\n};\n';
const target = path.join(root, 'server/src/game_content_seed.ts');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output) throw Error('Game content seed is stale; run node scripts/build-game-content.cjs');
} else fs.writeFileSync(target, output);
console.log('PASS game content seed: ' + rows.game_items.length + ' items, ' + rows.game_crops.length + ' crops, ' +
  Object.keys(source.loot).length + ' loot tables, ' + rows.game_recipes.length + ' recipes');
